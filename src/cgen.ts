import type { Expr, FnDecl, Program, Stmt, VarSym } from './ast.ts';
import type { Type } from './types.ts';

const PRELUDE = String.raw`/* generated by lumen */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <stdbool.h>
#include <math.h>

#define LM_MAXSAFE 9007199254740991LL

static void lm_die(const char *msg) {
  fflush(stdout);
  fprintf(stderr, "runtime error: %s\n", msg);
  exit(1);
}

static long long lm_chk(long long r, int ovf) {
  if (ovf || r > LM_MAXSAFE || r < -LM_MAXSAFE) lm_die("integer overflow");
  return r;
}
static long long lm_add(long long a, long long b) { long long r; int o = __builtin_add_overflow(a, b, &r); return lm_chk(r, o); }
static long long lm_sub(long long a, long long b) { long long r; int o = __builtin_sub_overflow(a, b, &r); return lm_chk(r, o); }
static long long lm_mul(long long a, long long b) { long long r; int o = __builtin_mul_overflow(a, b, &r); return lm_chk(r, o); }
static long long lm_div(long long a, long long b) { if (b == 0) lm_die("division by zero"); return a / b; }
static long long lm_mod(long long a, long long b) { if (b == 0) lm_die("modulo by zero"); return a % b; }

static long long lm_f2i(double v) {
  if (isnan(v) || isinf(v) || fabs(v) > 9007199254740991.0) lm_die("float out of range for int");
  return (long long)v;
}

static const char *lm_cat(const char *a, const char *b) {
  size_t la = strlen(a), lb = strlen(b);
  char *r = (char *)malloc(la + lb + 1);
  memcpy(r, a, la);
  memcpy(r + la, b, lb + 1);
  return r;
}

static const char *lm_str_int(long long v) {
  char buf[32];
  snprintf(buf, sizeof buf, "%lld", v);
  return strdup(buf);
}

/* same output as the JS runtime: shortest round-trip digits, js exponent rules */
static const char *lm_str_float(double v) {
  char tmp[64], buf[400];
  if (isnan(v)) return "NaN";
  if (isinf(v)) return v < 0 ? "-Infinity" : "Infinity";
  if (v == 0) return "0.0";
  int p;
  for (p = 1; p <= 17; p++) {
    snprintf(tmp, sizeof tmp, "%.*e", p - 1, v);
    if (strtod(tmp, NULL) == v) break;
  }
  char *e = strchr(tmp, 'e');
  int ex = atoi(e + 1);
  if (ex >= -6 && ex < 21) {
    int dec = p - 1 - ex;
    snprintf(buf, sizeof buf, "%.*f", dec < 0 ? 0 : dec, v);
    if (!strchr(buf, '.')) strcat(buf, ".0");
  } else {
    *e = 0;
    snprintf(buf, sizeof buf, "%se%c%d", tmp, ex < 0 ? '-' : '+', abs(ex));
  }
  return strdup(buf);
}

static const char *lm_str_bool(bool v) { return v ? "true" : "false"; }

static void lm_print_int(long long v) { printf("%lld\n", v); }
static void lm_print_float(double v) { puts(lm_str_float(v)); }
static void lm_print_bool(bool v) { puts(v ? "true" : "false"); }
static void lm_print_string(const char *s) { puts(s); }

static long long lm_len(const char *s) { return (long long)strlen(s); }
`;

const CTYPE: Record<Type, string> = {
  int: 'long long',
  float: 'double',
  bool: 'bool',
  string: 'const char *',
  void: 'void',
  error: 'void',
};

const OPS: Record<string, string> = { '==': '==', '!=': '!=', '<': '<', '<=': '<=', '>': '>', '>=': '>=' };
const INT_FN: Record<string, string> = { '+': 'lm_add', '-': 'lm_sub', '*': 'lm_mul', '/': 'lm_div', '%': 'lm_mod' };

function hasCall(e: Expr): boolean {
  switch (e.k) {
    case 'call': return true;
    case 'unary': return hasCall(e.arg);
    case 'binary': return hasCall(e.l) || hasCall(e.r);
    default: return false;
  }
}

const isConst = (e: Expr) => e.k === 'int' || e.k === 'float' || e.k === 'str' || e.k === 'bool';

function cString(s: string): string {
  let out = '"';
  for (const b of Buffer.from(s, 'utf8')) {
    if (b === 0x22) out += '\\"';
    else if (b === 0x5c) out += '\\\\';
    else if (b === 0x0a) out += '\\n';
    else if (b === 0x09) out += '\\t';
    else if (b === 0x0d) out += '\\r';
    else if (b >= 0x20 && b < 0x7f && b !== 0x3f) out += String.fromCharCode(b); // skip '?' to dodge trigraphs
    else out += '\\' + b.toString(8).padStart(3, '0');
  }
  return out + '"';
}

class Gen {
  lines: string[] = [];
  ind = 1;
  tmp = 0;
  names = new Map<VarSym, string>();
  uid = 0;

  name(v: VarSym): string {
    let n = this.names.get(v);
    if (!n) {
      n = (v.where === 'global' ? 'g_' : 'v_') + v.name + '_' + this.uid++;
      this.names.set(v, n);
    }
    return n;
  }

  line(s: string) {
    this.lines.push('  '.repeat(this.ind) + s);
  }

  // run fn with a fresh line buffer, hand back what it emitted
  capture<T>(fn: () => T): { lines: string[]; result: T } {
    const saved = this.lines;
    this.lines = [];
    const result = fn();
    const lines = this.lines;
    this.lines = saved;
    return { lines, result };
  }

  newTmp(ty: Type, init: string): string {
    const t = `t${this.tmp++}`;
    this.line(`${CTYPE[ty]} ${t} = ${init};`);
    return t;
  }

  // operands that come before a call must be evaluated first, so pin them to a temp
  pin(e: Expr, s: string, laterHasCall: boolean): string {
    return laterHasCall && !isConst(e) ? this.newTmp(e.ty, s) : s;
  }

  expr(e: Expr, asStmt = false): string {
    switch (e.k) {
      case 'int': return e.value < 0 ? `(${e.value}LL)` : `${e.value}LL`;
      case 'float': {
        const s = String(e.value);
        return s.includes('.') || s.includes('e') ? s : s + '.0';
      }
      case 'str': return cString(e.value);
      case 'bool': return e.value ? 'true' : 'false';
      case 'var': return this.name(e.sym!);

      case 'unary': {
        const a = this.expr(e.arg);
        return e.op === '!' ? `(!${a})` : `(-${a})`;
      }

      case 'binary': {
        if (e.op === '&&' || e.op === '||') {
          const l = this.expr(e.l);
          if (!hasCall(e.r)) return `(${l} ${e.op} ${this.expr(e.r)})`;
          const t = this.newTmp('bool', l);
          this.line(e.op === '&&' ? `if (${t}) {` : `if (!${t}) {`);
          this.ind++;
          const r = this.expr(e.r);
          this.line(`${t} = ${r};`);
          this.ind--;
          this.line('}');
          return t;
        }

        const rc = hasCall(e.r);
        const l = this.pin(e.l, this.expr(e.l), rc);
        const r = this.expr(e.r);
        const ty = e.l.ty;
        if (e.op === '+' && ty === 'string') return `lm_cat(${l}, ${r})`;
        if (e.op === '==' && ty === 'string') return `(strcmp(${l}, ${r}) == 0)`;
        if (e.op === '!=' && ty === 'string') return `(strcmp(${l}, ${r}) != 0)`;
        if (OPS[e.op]) return `(${l} ${OPS[e.op]} ${r})`;
        if (ty === 'int') return `${INT_FN[e.op]}(${l}, ${r})`;
        return `(${l} ${e.op} ${r})`;
      }

      case 'call': return this.call(e, asStmt);
    }
  }

  call(e: Extract<Expr, { k: 'call' }>, asStmt: boolean): string {
    const args: string[] = [];
    e.args.forEach((a, i) => {
      const later = e.args.slice(i + 1).some(hasCall);
      args.push(this.pin(a, this.expr(a), later));
    });

    let text: string;
    if (e.builtin) {
      const aty = e.args[0].ty;
      const a = args[0];
      switch (e.builtin) {
        case 'print': text = `lm_print_${aty}(${a})`; break;
        case 'str': text = aty === 'string' ? a : `lm_str_${aty}(${a})`; break;
        case 'int': text = aty === 'int' ? a : `lm_f2i(${a})`; break;
        case 'float': text = aty === 'float' ? a : `((double)${a})`; break;
        case 'len': text = `lm_len(${a})`; break;
      }
    } else {
      text = `f_${e.fn!.name}(${args.join(', ')})`;
    }

    if (e.ty === 'void') {
      this.line(text + ';');
      return '';
    }
    if (asStmt) {
      this.line(`(void)${text};`);
      return '';
    }
    return this.newTmp(e.ty, text);
  }

  block(body: Stmt[]) {
    for (const s of body) this.stmt(s);
  }

  stmt(s: Stmt) {
    switch (s.k) {
      case 'fn': return;

      case 'let': {
        const v = this.expr(s.init);
        const sym = s.sym!;
        if (sym.where === 'global') this.line(`${this.name(sym)} = ${v};`);
        else this.line(`${CTYPE[sym.ty]} ${this.name(sym)} = ${v};`);
        return;
      }

      case 'assign': {
        const v = this.expr(s.value);
        this.line(`${this.name(s.sym!)} = ${v};`);
        return;
      }

      case 'expr': {
        const v = this.expr(s.e, true);
        if (v && s.e.k !== 'call') this.line(`(void)(${v});`);
        return;
      }

      case 'if': {
        const c = this.expr(s.cond);
        this.line(`if (${c}) {`);
        this.ind++;
        this.block(s.then);
        this.ind--;
        if (s.els) {
          this.line('} else {');
          this.ind++;
          this.block(s.els);
          this.ind--;
        }
        this.line('}');
        return;
      }

      case 'while': {
        const { lines: pre, result: c } = this.capture(() => {
          this.ind++;
          const r = this.expr(s.cond);
          this.ind--;
          return r;
        });
        if (pre.length === 0) {
          this.line(`while (${c}) {`);
          this.ind++;
        } else {
          // condition needs statements (a call), so re-evaluate at the top of every iteration
          this.line('while (1) {');
          this.ind++;
          this.lines.push(...pre);
          this.line(`if (!(${c})) break;`);
        }
        this.block(s.body);
        this.ind--;
        this.line('}');
        return;
      }

      case 'return':
        if (s.value) {
          const v = this.expr(s.value);
          this.line(`return ${v};`);
        } else {
          this.line('return;');
        }
        return;

      case 'break': this.line('break;'); return;
      case 'continue': this.line('continue;'); return;

      case 'block':
        this.line('{');
        this.ind++;
        this.block(s.body);
        this.ind--;
        this.line('}');
        return;
    }
  }

  fnSig(f: FnDecl): string {
    const ps = f.params.map(p => `${CTYPE[p.ty]} ${this.name(p.sym!)}`).join(', ');
    return `static ${CTYPE[f.ret]} f_${f.name}(${ps || 'void'})`;
  }
}

export function emitC(prog: Program): string {
  const g = new Gen();
  const fns = prog.fns.filter(f => f.sym);
  const out: string[] = [PRELUDE];

  // pre-name params and globals so prototypes and bodies agree
  for (const f of fns) out.push(g.fnSig(f) + ';');
  out.push('');

  const globals = new Set<VarSym>();
  for (const s of prog.body) {
    if (s.k === 'let' && s.sym && s.sym.where === 'global') globals.add(s.sym);
  }
  for (const v of globals) out.push(`static ${CTYPE[v.ty]} ${g.name(v)};`);
  if (globals.size) out.push('');

  for (const f of fns) {
    g.lines = [];
    g.ind = 1;
    g.block(f.body);
    out.push(g.fnSig(f) + ' {', ...g.lines, '}', '');
  }

  g.lines = [];
  g.ind = 1;
  g.block(prog.body);
  out.push('int main(void) {', ...g.lines, '  return 0;', '}', '');
  return out.join('\n');
}
